"""Imports Material Symbols (Rounded) as Android VectorDrawables.

Usage: tools/import_icons.py
Downloads each symbol listed in ICONS (filled, habit icons) and UI_ICONS
(outlined, app chrome) from the google/material-design-icons repository
(Apache License 2.0) and writes res/drawable/ic_habit_<key>.xml and
res/drawable/ic_ui_<name>.xml. Re-run after editing the lists; keep ICONS in
sync with HabitIcons.kt.

Path data is rewritten with explicit separators: Android 5.x cannot parse the
compact form Material Symbols use (e.g. "7.5.5" meaning 7.5 and .5).
"""
