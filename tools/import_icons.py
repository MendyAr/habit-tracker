UI_ICONS = [
    "add", "add_photo_alternate", "add_to_home_screen", "arrow_back", "calendar_month",
    "check", "chevron_left", "chevron_right", "close", "delete", "edit", "expand_more",
    "format_list_bulleted", "widgets",
]

BASE = ("https://raw.githubusercontent.com/google/material-design-icons/master/"
        "symbols/web/{0}/materialsymbolsrounded/{0}{1}_24px.svg")
OUT = pathlib.Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols "{symbol}" (Rounded{style}), Apache License 2.0. Generated by tools/import_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
{paths}
    </group>
</vector>
"""


NUMBER = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")
TOKEN = re.compile(r"[A-Za-z]|" + NUMBER.pattern)


def normalize(path_data):
    """Re-emits path data with every command and number separated by a space."""
    tokens = TOKEN.findall(path_data)
    if "".join(tokens) != re.sub(r"[\s,]", "", path_data):
        raise ValueError(f"unexpected path data: {path_data[:60]}")
    # Leading zeros ("-0.5" rather than "-.5") keep old parsers on the safe side.
    return " ".join(re.sub(r"^([-+]?)\.", r"\g<1>0.", t) for t in tokens)


def write(name, symbol, filled, fill_color):
    svg = urllib.request.urlopen(BASE.format(symbol, "_fill1" if filled else "")).read().decode()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    body = "\n".join(
        f'        <path\n            android:fillColor="{fill_color}"\n'
        f'            android:pathData="{normalize(d)}" />' for d in paths)
    style = ", filled" if filled else ""
    (OUT / f"{name}.xml").write_text(TEMPLATE.format(symbol=symbol, style=style, paths=body))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for key, symbol in ICONS.items():
        write(f"ic_habit_{key}", symbol, filled=True, fill_color="@android:color/white")
    for symbol in UI_ICONS:
        write(f"ic_ui_{symbol}", symbol, filled=False, fill_color="@color/text_primary")
    print(f"wrote {len(ICONS) + len(UI_ICONS)} icons to {OUT}")


if __name__ == "__main__":
    main()
